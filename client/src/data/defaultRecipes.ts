function ing(foodName: string, grossWeight: number, fc = 1.0) {
  return {
    id: `seed-${foodName.toLowerCase().replace(/\s+/g, '-').replace(/[^\w-]/g, '')}`,
    foodId: `seed-food-${foodName.toLowerCase().replace(/\s+/g, '-').replace(/[^\w-]/g, '')}`,
    foodName,
    grossWeight,
    netWeight: Math.round(grossWeight / fc),
    correctionFactor: fc,
    estimatedCost: 0,
  };
}

function nut(kcal: number, ptn: number, lip: number, cho: number, fib: number, ca: number, fe: number, zn: number, vitA: number, vitC: number) {
  return { kcal, protein: ptn, lipids: lip, carbohydrates: cho, fiber: fib, calcium: ca, iron: fe, zinc: zn, vitaminA: vitA, vitaminC: vitC };
}

